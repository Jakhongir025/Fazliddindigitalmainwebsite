'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..'),out=path.join(root,'public');
fs.mkdirSync(out,{recursive:true});
for(const name of ['index.html','img','icons'])fs.cpSync(path.join(root,name),path.join(out,name),{recursive:true});
const {renderMeta}=require('./meta-config');
const meta=renderMeta(fs.readFileSync(path.join(root,'index.html'),'utf8'),process.env);
fs.writeFileSync(path.join(out,'index.html'),meta.html);
const pixelFile=path.join(out,'meta-pixel.js');
if(meta.pixelEnabled)fs.copyFileSync(path.join(root,'meta-pixel.js'),pixelFile);
else if(fs.existsSync(pixelFile))fs.unlinkSync(pixelFile);
console.log('Public output contains only the page and image assets.');
